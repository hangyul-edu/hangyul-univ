import { docLabel, essayLabel, useLocale } from '@hangyul/i18n';
import type { IntakeTerm, MatchReason } from '@hangyul/types';

/** Student app translation hook: `t('dashboard.title')` reads the student namespace, `t('common:…')` shared vocabulary. */
export function useT() {
  return useLocale(['student', 'common']);
}

export type TFn = (key: string, opts?: Record<string, unknown>) => string;

/** Translate a match reason by code; fall back to the API's English text when no translation exists. */
export function reasonText(t: TFn, r: Pick<MatchReason, 'code' | 'text' | 'params'>): string {
  // Language gaps name the exact requirement and the student's own score ("TOPIK 3 required — you have TOPIK 2").
  const p = (r.params ?? {}) as Record<string, number | null | undefined>;
  if ((r.code === 'LANGUAGE_GAP_SMALL' || r.code === 'LANGUAGE_BELOW') && p.min_topik) {
    return p.have_topik ? t('gap.topik', { min: p.min_topik, have: p.have_topik }) : t('gap.topikNone', { min: p.min_topik });
  }
  if ((r.code === 'LANGUAGE_GAP_SMALL' || r.code === 'LANGUAGE_BELOW') && p.min_ielts) {
    return p.have_ielts ? t('gap.ielts', { min: p.min_ielts, have: p.have_ielts }) : t('gap.ieltsNone', { min: p.min_ielts });
  }
  const s = t(`common:matchReason.${r.code}`, { ...(r.params ?? {}), defaultValue: '' });
  return s && !s.includes('{{') ? s : r.text;
}

export function intakeLabel(t: TFn, term: IntakeTerm | string, year: number | string): string {
  return t('common:intakeLabel', { term: t(`common:term.${term}`), year });
}

/** Translate a dynamic key and fall back to a provided string (API text) if it is missing. */
export function tr(t: TFn, key: string, fallback: string, opts?: Record<string, unknown>): string {
  const s = t(key, { ...localizeParams(t, opts ?? {}), defaultValue: '' });
  return s && !s.includes('{{') ? s : fallback;
}

/**
 * API params carry English catalogue labels next to their codes (`label` + `category` / `essay_type`). Outside English
 * the label is replaced by the translated category or essay type, so no English requirement name leaks into a sentence.
 */
export function localizeParams(t: TFn, p: Record<string, unknown>): Record<string, unknown> {
  if (typeof p.label !== 'string') return p;
  if (typeof p.essay_type === 'string' && p.essay_type) return { ...p, label: essayLabel(t, { label: p.label, essay_type: p.essay_type }) };
  if (typeof p.category === 'string' && /^[A-Z_]+$/.test(p.category)) return { ...p, label: docLabel(t, { label: p.label, category: p.category }) };
  return p;
}

/**
 * Essay titles generated by Hangyul read "<essay type> — <university>" in English. Outside English the essay type part is
 * shown translated; a title the student wrote themselves is shown as written.
 */
export function essayTitle(t: TFn, e: { title: string; essay_type: string }, locale: string): string {
  if (locale.startsWith('en')) return e.title;
  const key = `common:essayType.${e.essay_type}`;
  const en = t(key, { lng: 'en', defaultValue: '' });
  if (!en) return e.title;
  if (e.title === en) return t(key);
  return e.title.startsWith(`${en} — `) ? `${t(key)}${e.title.slice(en.length)}` : e.title;
}

/** Notification params: a document or essay named in English by the API is named by its translated category/type. */
export function notifyParams(t: TFn, p: Record<string, unknown>, locale: string): Record<string, unknown> {
  const out = { ...p };
  if (locale.startsWith('en')) return out;
  if (typeof p.category === 'string' && typeof p.document === 'string' && p.category !== 'OTHER') out.document = t(`common:docCategory.${p.category}`, { defaultValue: p.document });
  if (typeof p.essay_type === 'string' && typeof p.title === 'string') out.title = essayTitle(t, { title: p.title, essay_type: p.essay_type }, locale);
  return out;
}
