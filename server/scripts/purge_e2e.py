"""Remove accounts created by end-to-end tests (``e2e-…@example.com``) and every row that depends on them.

E2E specs run against the live development stack, so without this the demo dataset slowly fills with test users
("Minh Anh E2E" in agency lists, payments and university applicants). The purge walks the foreign-key graph from the
``users`` table: it collects every row whose FK points at a row already marked for deletion (to a fixpoint), then
deletes children before parents. Rows that merely *mention* a test user through a nullable FK are nulled instead of
deleted when the FK is optional and the row is not otherwise owned by the test user.

V4: E2E specs also act with *seeded* accounts on *seeded* applications (a university admin asking the demo applicant
Priya Nair for a document). Those rows belong to no E2E account, so the FK walk above never finds them. Specs therefore
mark what they write with a stable ``E2E`` prefix in the label/note, and ``purge_marked_requests`` removes every marked
document request together with its generated task, notifications, analytics/audit rows and the status-history rows it
caused — and restores the application's status to what it was before the request. Notifications sent to seeded staff
that name an E2E account ("New student assigned: Minh Anh E2E") are removed as well.

Usage:  python scripts/purge_e2e.py [--dry-run]
"""
from __future__ import annotations

import re
import sys
from collections import Counter, defaultdict
from datetime import timedelta
from pathlib import Path

from sqlalchemy import delete, func, or_, select, update

sys.path.insert(0, ".")

from app.core.config import get_settings  # noqa: E402
from app.core.db import SessionLocal  # noqa: E402
from app.models import (  # noqa: E402
    AnalyticsEvent,
    Application,
    ApplicationStatusHistory,
    AuditLog,
    Base,
    Conversation,
    DocumentRequest,
    Message,
    Notification,
    Task,
    User,
)

PATTERN = "e2e-%@example.com"
# V24: accounts the release gates and native sign-up checks register on each run. Each address is generated by one
# script (scripts/qa/v21/toss-test-transaction.mjs, the V22 gate, the native sign-up integration test) and never by a
# person; left behind, auto-routing put six "V21 Payment Probe" students on the Lotus Bridge roster (REPORT §290 V24-1).
GATE_PATTERNS = ("native-%@example.com", "qa-v22-%@example.com", "v21pay+%@demo.hangyul.kr")
# FKs that only record *who* did something (actor/reviewer/author on someone else's record) — null them, don't delete.
SOFT_COLUMNS = {"actor_user_id", "reviewer_user_id", "university_reviewer_id", "uploaded_by_id", "created_by_user_id", "assigned_by_user_id"}


# The marker E2E specs put at the start of anything they write on seeded data (label or note).
E2E_MARK = re.compile(r"^E2E\b")
# Before V4 one spec stamped only ``(<Date.now()>)`` at the end of the note; recognise that legacy form too.
LEGACY_STAMP = re.compile(r"\(1\d{12}\)\.?$")
WINDOW = timedelta(seconds=10)


# V24: e2e/v5-dossier.spec.ts stamps the *label* instead ("Bank balance certificate 1792877708454").
LABEL_STAMP = re.compile(r" 1\d{12}$")


def is_e2e_request(label: str | None, note: str | None) -> bool:
    return bool(E2E_MARK.match(label or "") or E2E_MARK.match(note or "") or LEGACY_STAMP.search((note or "").strip())
                or LABEL_STAMP.search((label or "").strip()))


def _near(col, at):
    return col.between(at - WINDOW, at + WINDOW)


def purge_marked_requests(db, dry: bool = False) -> Counter:
    """Remove E2E-marked document requests on (seeded) applications and everything they caused. Returns row counts."""
    counts: Counter = Counter()
    reqs = [r for r in db.scalars(select(DocumentRequest)).all() if is_e2e_request(r.label, r.note)]
    removed_history: dict = defaultdict(list)
    doomed: dict[type, set] = defaultdict(set)
    for r in reqs:
        app_link = f"/applications/{r.application_id}"
        doomed[DocumentRequest].add(r.id)
        doomed[Task] |= set(db.scalars(select(Task.id).where((Task.dedupe_key == f"docreq:{r.id}") | (Task.id == r.task_id))).all())
        moments = [m for m in (r.requested_at, r.fulfilled_at, r.cancelled_at) if m]
        for m in moments:
            doomed[Notification] |= set(db.scalars(select(Notification.id).where(
                Notification.kind == "DOCUMENT_REQUEST", Notification.link == app_link, _near(Notification.created_at, m),
                Notification.fallback_text.contains(r.label))).all())
            doomed[AnalyticsEvent] |= set(db.scalars(select(AnalyticsEvent.id).where(
                AnalyticsEvent.name.like("document_request%"), AnalyticsEvent.application_id == r.application_id,
                _near(AnalyticsEvent.occurred_at, m))).all())
            doomed[AuditLog] |= set(db.scalars(select(AuditLog.id).where(
                AuditLog.action.like("application.document_request%"), AuditLog.entity_id == str(r.application_id),
                _near(AuditLog.created_at, m))).all())
        # The request moved the application (SUBMITTED → UNIVERSITY_REVIEW → ADDITIONAL_DOCUMENTS) in the same instant.
        for h in db.scalars(select(ApplicationStatusHistory).where(
                ApplicationStatusHistory.application_id == r.application_id, ApplicationStatusHistory.actor_org_type == "UNIVERSITY",
                _near(ApplicationStatusHistory.created_at, r.requested_at))).all():
            if h.created_at == r.requested_at or (h.note or "").startswith(f"Requested: {r.label}"):
                doomed[ApplicationStatusHistory].add(h.id)
                removed_history[r.application_id].append(h)
    # Staff notifications that name an E2E account (the account itself is purged by the FK walk).
    doomed[Notification] |= set(db.scalars(select(Notification.id).where(Notification.fallback_text.op("~")(r"\mE2E\M"))).all())
    restored: list[tuple] = []
    for app_id, hist in list(removed_history.items()):
        # A genuine request made after the E2E one relies on the status it found: keep the history and status as they are.
        if db.scalars(select(DocumentRequest.id).where(DocumentRequest.application_id == app_id,
                                                       DocumentRequest.id.not_in(list(doomed[DocumentRequest])))).first():
            doomed[ApplicationStatusHistory] -= {h.id for h in hist}
            continue
        app = db.get(Application, app_id)
        removed_ids = {h.id for h in hist}
        remaining = [h for h in db.scalars(select(ApplicationStatusHistory).where(ApplicationStatusHistory.application_id == app_id)
                                          .order_by(ApplicationStatusHistory.created_at)).all() if h.id not in removed_ids]
        # Only restore when nothing else changed the status after the E2E request.
        if app and remaining and app.status in {h.to_status for h in hist} and all(h.created_at <= min(x.created_at for x in hist) for h in remaining):
            restored.append((app, remaining[-1].to_status))
    for model, ids in doomed.items():
        counts[model.__tablename__] = len(ids)
    counts["applications_restored"] = len(restored)
    if dry or (not reqs and not doomed[Notification]):
        return counts
    for app, status in restored:
        app.status = status
    for model in (Notification, AnalyticsEvent, AuditLog, ApplicationStatusHistory, DocumentRequest, Task):
        if doomed[model]:
            db.execute(delete(model).where(model.id.in_(list(doomed[model]))))
    db.flush()
    # Keep derived state honest: readiness counts open requests; auto-tasks follow the application status.
    from app.services.document_requests import _refresh_readiness
    from app.services.tasks_engine import generate_for_student

    for app_id in {r.application_id for r in reqs}:
        app = db.get(Application, app_id)
        if app:
            _refresh_readiness(db, app)
            generate_for_student(db, app.student_user_id)
    return counts


def purge_accounts(db, dry: bool) -> None:
    tables = Base.metadata.sorted_tables  # parents before children
    user_ids = set(db.scalars(select(User.id).where(or_(*(User.email.like(p) for p in (PATTERN, *GATE_PATTERNS))))).all())
    if not user_ids:
        print("No e2e accounts found.")
        return
    doomed: dict[str, set] = defaultdict(set)
    doomed["users"] = set(user_ids)
    soft: list[tuple] = []
    changed = True
    while changed:
        changed = False
        for t in tables:
            pk = list(t.primary_key.columns)
            if len(pk) != 1:
                continue
            for fk in t.foreign_keys:
                target = fk.column.table.name
                ids = doomed.get(target)
                if not ids:
                    continue
                col = fk.parent
                if col.name in SOFT_COLUMNS and col.nullable and t.name != target:
                    soft.append((t, col, target))
                    continue
                rows = set(db.scalars(select(pk[0]).where(col.in_(list(ids)))).all()) - doomed[t.name]
                if rows:
                    doomed[t.name] |= rows
                    changed = True
    total = sum(len(v) for v in doomed.values())
    print(f"e2e accounts: {len(user_ids)}; rows to delete: {total} across {len([k for k, v in doomed.items() if v])} tables")
    if dry:
        for name, ids in sorted(doomed.items()):
            if ids:
                print(f"  {name}: {len(ids)}")
        return
    for t, col, target in soft:
        db.execute(update(t).where(col.in_(list(doomed[target]))).values({col.name: None}))
    for t in reversed(tables):
        ids = doomed.get(t.name)
        if ids:
            pk = list(t.primary_key.columns)[0]
            db.execute(delete(t).where(pk.in_(list(ids))))
    db.flush()
    print("Purged e2e accounts.")


# V26: rows release gates write on *seeded* records under no test account — a gate's own message on a seeded thread
# ("qa-v22 reply <stamp> a", scripts/qa/v22-gate.mjs) and staff notifications naming an account that was already purged
# ("New student assigned: V21 Payment Probe"). Neither has an FK path to a test user, so purge_accounts never sees them;
# both were visible in the demo data on 2026-10-27 (REPORT §330). Each marker is written by a script, never by a person.
GATE_MESSAGE = r"^qa-v[0-9]+ "
GATE_NAMES = ("V21 Payment Probe", "Native Signup", "QA V22")
GATE_TEXT = r"(" + "|".join(GATE_NAMES) + r"|\mE2E\M)"


def residue_queries():
    """(label, model, where-clause) for every kind of QA residue — the purge deletes them, `--check` counts them."""
    return [
        ("test accounts", User, or_(*(User.email.like(p) for p in (PATTERN, *GATE_PATTERNS)))),
        ("gate messages on seeded threads", Message, Message.body.op("~")(GATE_MESSAGE)),
        ("notifications naming test accounts", Notification, Notification.fallback_text.op("~")(GATE_TEXT)),
        ("E2E-marked document requests", DocumentRequest, or_(DocumentRequest.label.op("~")(r"^E2E\M"), DocumentRequest.note.op("~")(r"^E2E\M"))),
    ]


def purge_gate_markers(db, dry: bool) -> Counter:
    counts: Counter = Counter()
    for label, model, where in residue_queries()[1:3]:
        ids = list(db.scalars(select(model.id).where(where)).all())
        counts[label] = len(ids)
        if ids and not dry:
            convs = set(db.scalars(select(Message.conversation_id).where(Message.id.in_(ids))).all()) if model is Message else set()
            db.execute(delete(model).where(model.id.in_(ids)))
            for cid in convs:  # the thread's "last message" must not keep pointing at a deleted gate message
                last = db.scalar(select(func.max(Message.created_at)).where(Message.conversation_id == cid))
                db.execute(update(Conversation).where(Conversation.id == cid).values(last_message_at=last))
    return counts


def orphan_upload_files(db) -> list[Path]:
    """Files under the storage directory that no document version or message attachment references.

    V26 (REPORT §341): purging *rows* left the *files* — 15,488 of them (9.4 MB) on 2026-10-28, written by e2e and gate
    uploads whose rows were purged (or that belonged to the throw-away e2e database, which shares the directory)."""
    from app.models import DocumentVersion, MessageAttachment

    root = Path(get_settings().storage_dir)
    if not root.is_dir():
        return []
    referenced = {Path(k).name for k in db.scalars(select(DocumentVersion.storage_key)).all() if k}
    referenced |= {Path(k).name for k in db.scalars(select(MessageAttachment.storage_key)).all() if k}
    return [f for f in root.rglob("*") if f.is_file() and f.name not in referenced]


def purge_orphan_files(db, dry: bool) -> int:
    files = orphan_upload_files(db)
    if not dry:
        for f in files:
            f.unlink(missing_ok=True)
        # empty per-student directories go too
        for d in sorted((p for p in Path(get_settings().storage_dir).rglob("*") if p.is_dir()), key=lambda p: -len(p.parts)):
            if not any(d.iterdir()):
                d.rmdir()
    return len(files)


def check() -> int:
    """`--check`: count residue without changing anything; exit 1 if any exists (qa:v26 TEST HYGIENE)."""
    with SessionLocal() as db:
        bad = 0
        for label, model, where in residue_queries():
            n = db.scalar(select(func.count()).select_from(model).where(where)) or 0
            print(f"{label}: {n}")
            bad += n
        n = len(orphan_upload_files(db))
        print(f"upload files no row references: {n}")
        bad += n
        return 1 if bad else 0


def main(dry: bool) -> None:
    with SessionLocal() as db:
        purge_accounts(db, dry)
        markers = purge_gate_markers(db, dry)
        print(f"Gate markers on seeded data{' (dry run)' if dry else ''}: {dict(markers) or 'none'}")
        counts = purge_marked_requests(db, dry)
        marked = {k: v for k, v in counts.items() if v}
        print(f"E2E rows on seeded data{' (dry run)' if dry else ''}: {marked or 'none'}")
        print(f"Orphan upload files{' (dry run)' if dry else ''}: {purge_orphan_files(db, dry)}")
        if dry:
            db.rollback()
        else:
            db.commit()


if __name__ == "__main__":
    if "--check" in sys.argv:
        sys.exit(check())
    main("--dry-run" in sys.argv)
