// Regenerates src/resources.ts: a static map of lazy JSON loaders (works in Vite and Metro).
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const localesDir = join(root, 'locales');
const lines = ['// GENERATED by scripts/gen-resources.mjs — do not edit.', 'export const loaders: Record<string, Record<string, () => Promise<unknown>>> = {'];
for (const loc of readdirSync(localesDir).filter((d) => !d.startsWith('_')).sort()) {
  const dir = join(localesDir, loc);
  const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.json')).sort() : [];
  if (!files.length) continue;
  lines.push(`  '${loc}': {`);
  for (const f of files) lines.push(`    '${f.replace('.json', '')}': () => import('../locales/${loc}/${f}'),`);
  lines.push('  },');
}
lines.push('};', '');
writeFileSync(join(root, 'src/resources.ts'), lines.join('\n'));
console.log('resources.ts regenerated');
