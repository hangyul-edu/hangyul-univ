writeFileSync(join(here, '../tokens.css'), `/* GENERATED by scripts/build-css.mjs — do not edit. Source: src/index.ts */\n:root {\n${lines.join('\n')}\n  color-scheme: light;\n}\n${dark}`);
console.log(`tokens.css written (${lines.length} variables)`);
