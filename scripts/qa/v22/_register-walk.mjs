// V22 — drive the real four-step registration in a browser and screenshot each step.
// Usage: node scripts/qa/v22/_register-walk.mjs <width> <locale> <nationality> <phone_country> <local_phone> <out-prefix>
import { execSync } from 'node:child_process';
import { chromium } from '@playwright/test';
const [w = '390', locale = 'en', nat = 'NP', pc = 'NP', local = '9841234567', out = 'docs/qa/v22/shots/register'] = process.argv.slice(2);
const H = { 390: 844, 768: 1024, 1024: 768, 1440: 900, 1728: 1080 };
const API = 'http://localhost:8001/api/v1';
const q = (sql) => execSync(`psql postgresql://hangyul:hangyul_dev@localhost:5432/hangyul_univ -At -c "${sql}"`).toString().trim();
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: Number(w), height: H[w] ?? 900 }, locale });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
await p.goto('http://localhost:3101/register');
await p.evaluate((l) => localStorage.setItem('hg.locale', l), locale);
await p.goto(`http://localhost:3101/register?lang=${locale}`, { waitUntil: 'networkidle' });
const email = `walk-${Date.now()}@example.com`;
await p.fill('#full_name', 'Aarati Shrestha');
await p.fill('#email', email);
await p.click('.hg-phone__country');
await p.fill('.hg-phone__search input', pc);
await p.locator('.hg-phone__opt').first().click();
await p.fill('#phone_local', local);
await p.fill('#password', 'a sentence i remember');
await p.fill('#password_confirm', 'a sentence i remember');
// nationality: the shared CountrySelect is a button + search + listbox
await p.locator('button.hg-select').first().click();
await p.locator('[role=listbox]').locator('xpath=..').locator('input').fill(nat);
await p.locator('[role=listbox] [role=option]').first().click();
await p.screenshot({ path: `${out}-${w}-${locale}-1-account.png`, fullPage: true });
await p.click('button[type=submit]');
await p.waitForSelector('.st-reg__chan', { timeout: 15000 });
await p.waitForTimeout(1200);
await p.screenshot({ path: `${out}-${w}-${locale}-2-verify.png`, fullPage: true });
const emailCid = q(`select id from verification_challenges where target='${email}' and purpose='SIGNUP_EMAIL' order by created_at desc limit 1`);
const phoneCid = q(`select id from verification_challenges where purpose='SIGNUP_PHONE' and consumed_at is null and invalidated_at is null order by created_at desc limit 1`);
const code = async (cid) => (await (await fetch(`${API}/auth/verification/peek/${cid}`)).json()).code;
await p.fill('#otp-email', await code(emailCid));
await p.locator('section:has(#otp-email) button.hg-btn--primary').click();
await p.waitForSelector('section[data-verified="true"]', { timeout: 10000 });
await p.fill('#otp-sms', await code(phoneCid));
await p.locator('section:has(#otp-sms) button.hg-btn--primary').click();
await p.waitForFunction(() => document.querySelectorAll('section[data-verified="true"]').length === 2, null, { timeout: 10000 });
await p.waitForTimeout(400);
await p.screenshot({ path: `${out}-${w}-${locale}-2-verified.png`, fullPage: true });
await p.locator('button.hg-btn--primary.hg-btn--lg:not([disabled])').last().click();
await p.waitForSelector('.hg-consents', { timeout: 10000 });
await p.screenshot({ path: `${out}-${w}-${locale}-3-consent.png`, fullPage: true });
const boxes = await p.locator('.hg-consents__list input[type=checkbox]').all();
for (const bx of boxes) { if (await bx.evaluate((el) => !!el.closest('li')?.querySelector('.is-required'))) await bx.check(); }
await p.locator('.hg-row button.hg-btn--primary').click();
await p.waitForSelector('.st-reg__done', { timeout: 20000 });
await p.waitForTimeout(300);
await p.screenshot({ path: `${out}-${w}-${locale}-4-done.png`, fullPage: true });
const me = q(`select email||' '||phone||' '||(email_verified_at is not null)||' '||(phone_verified_at is not null) from users where email='${email}'`);
const consents = q(`select purpose||':'||granted||':'||coalesce(locale,'')||':'||coalesce(document_version,'')||':'||coalesce(source,'') from consent_records where user_id=(select id from users where email='${email}') order by purpose`);
console.log(JSON.stringify({ email, me, consents: consents.split('\n'), errors: errs }, null, 1));
await b.close();
