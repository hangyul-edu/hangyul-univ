import { chromium } from '@playwright/test';
const B='http://localhost:3103', out='docs/qa/v6/university/after';
const b=await chromium.launch(); const ctx=await b.newContext({viewport:{width:390,height:844}}); const p=await ctx.newPage();
await p.goto(B+'/login');
const r=await p.request.post(B+'/api/v1/auth/demo-login',{data:{email:'admissions@pusan.univ.demo.hangyul.kr',client:'university'}});
const tok=(await r.json()).access_token;
const l=await (await p.request.get(B+'/api/v1/applications?status=UNIVERSITY_REVIEW&page_size=5',{headers:{Authorization:'Bearer '+tok}})).json();
await p.goto(B+'/applications/'+l.items[0].id,{waitUntil:'networkidle'});
await p.getByRole('button',{name:'Request documents'}).first().click(); await p.waitForTimeout(500);
await p.screenshot({path:out+'/un-phone-request-390.png'});
console.log('submit visible', await p.getByRole('button',{name:/Send request/i}).isVisible().catch(()=>false));
await p.keyboard.press('Escape'); await p.waitForTimeout(300);
await p.getByRole('button',{name:'Make offer'}).click(); await p.waitForTimeout(500);
await p.screenshot({path:out+'/un-phone-decision-390.png'});
console.log('confirm visible', await p.getByRole('button',{name:'Confirm'}).isVisible());
await b.close();
