/**
 * V19 — **signed-in** runtime verification of the native student app (REPORT §194.7; the brief's §34).
 *
 * V18 got as far as the login screen of the release APK and said so: the release build correctly refuses
 * the cleartext dev API, and the debug variant that would have allowed it ran out of memory. Both halves
 * of that are addressed here rather than worked around:
 *
 *   - The **debug variant** is used, because React Native's `android/app/src/debug/AndroidManifest.xml`
 *     sets `usesCleartextTraffic="true"` while the main manifest does not. That is exactly the "internal
 *     QA variant explicitly allowing the dev API" the brief asks for, and it leaves production networking
 *     untouched — the release build still refuses cleartext, which `qa:v18` asserts separately.
 *   - The build runs with the web dev servers stopped, and with
 *     `reactNativeArchitectures=x86_64` in the generated `android/gradle.properties`, which is what makes
 *     it fit in this environment at all: compiling the CMake targets for four ABIs is most of the build,
 *     and the emulator is x86_64. **The resulting APK is therefore emulator-only and is not a
 *     distributable artifact** — it lives in `android/app/build/outputs/` and is never copied into
 *     `result/`. `android/` is build output, regenerated by `expo prebuild`, so nothing about the release
 *     path is touched.
 *
 * Driving is done through `adb` + `uiautomator dump`: find a node by its text or content-description,
 * tap the centre of its bounds, screenshot, repeat. No Appium, nothing extra to install.
 *
 *   node scripts/qa/v19/native-runtime.mjs [--avd hangyul-qa] [--keep]
 */
import { execFileSync, spawn } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('../../../', import.meta.url).pathname;
const SDK = process.env.ANDROID_HOME ?? '/root/android-sdk';
const ADB = join(SDK, 'platform-tools/adb');
const EMULATOR = join(SDK, 'emulator/emulator');
const PKG = 'kr.hangyul.univ.student';
const APK = join(ROOT, 'apps/student-mobile/android/app/build/outputs/apk/debug/app-debug.apk');
const OUT = join(ROOT, 'docs/qa/v19/screenshots/native');
const ARG = process.argv.slice(2);
const val = (n, d) => { const i = ARG.indexOf(n); return i >= 0 ? ARG[i + 1] : d; };
const AVD = val('--avd', 'hangyul-qa');

mkdirSync(OUT, { recursive: true });
const sh = (cmd, args, opts = {}) => execFileSync(cmd, args, { encoding: 'utf8', timeout: 180000, ...opts });
const adb = (...a) => sh(ADB, a);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const log = [];
const record = (step, status, detail = '') => {
  log.push({ step, status, detail });
  const mark = status === 'ok' ? '\x1b[32m✓\x1b[0m' : status === 'skip' ? '\x1b[33m•\x1b[0m' : '\x1b[31m✗\x1b[0m';
  console.log(`  ${mark} ${step}${detail ? `  — ${detail}` : ''}`);
};

if (!existsSync(APK)) {
  console.error(`No debug APK at ${APK}\nBuild it first:  cd apps/student-mobile/android && ./gradlew :app:assembleDebug`);
  process.exit(2);
}

/* ---------------------------------------------------------------------- boot */

console.log(`\n\x1b[1mNative signed-in runtime — AVD ${AVD}\x1b[0m\n`);
let booted = false;
try { booted = adb('devices').split('\n').some((l) => /emulator-\d+\s+device/.test(l)); } catch { /* adb not up */ }

let emu;
if (!booted) {
  emu = spawn(EMULATOR, ['-avd', AVD, '-no-window', '-no-audio', '-no-boot-anim',
    '-gpu', 'swiftshader_indirect', '-no-snapshot', '-memory', '1536'],
  { detached: true, stdio: 'ignore' });
  emu.unref();
  process.stdout.write('  … waiting for the emulator to boot');
  const deadline = Date.now() + 300000;
  while (Date.now() < deadline) {
    await sleep(5000);
    process.stdout.write('.');
    try {
      if (adb('shell', 'getprop', 'sys.boot_completed').trim() === '1') { booted = true; break; }
    } catch { /* not up yet */ }
  }
  process.stdout.write('\n');
}
if (!booted) { record('emulator boot', 'fail', 'did not reach sys.boot_completed in 5 minutes'); process.exit(1); }
record('emulator boot', 'ok', adb('shell', 'getprop', 'ro.build.version.release').trim() + ' / API ' + adb('shell', 'getprop', 'ro.build.version.sdk').trim());

/* ---------------------------------------------------------------------- install */

try { adb('uninstall', PKG); } catch { /* not installed */ }
adb('install', '-r', '-g', APK);
record('install debug APK', 'ok', `${(readFileSync(APK).length / 1048576).toFixed(1)} MB`);

/*
 * A **debug** APK does not carry its JS: React Native leaves `createBundleDebugJsAndAssets` out of the
 * debug variant, so the app loads its bundle from Metro at :8081 on first launch. That is a property of
 * the variant that makes signed-in testing possible at all (the release build refuses the cleartext dev
 * API, which is why V18 stopped at the login screen) — it just means Metro has to be running, and the
 * emulator has to be able to reach it.
 *
 * `adb reverse` maps the device's :8081 to the host's. The API itself needs no mapping: the app is built
 * with `EXPO_PUBLIC_API_URL=http://10.0.2.2:8001`, and 10.0.2.2 is the emulator's own route to the host
 * loopback. The reverse for :8001 is belt and braces.
 */
let metro;
if (!(await fetch('http://127.0.0.1:8081/status').then((r) => r.ok).catch(() => false))) {
  metro = spawn('npx', ['expo', 'start', '--port', '8081'],
    { cwd: join(ROOT, 'apps/student-mobile'), detached: true, stdio: 'ignore',
      env: { ...process.env, EXPO_PUBLIC_API_URL: 'http://10.0.2.2:8001', CI: '1' } });
  metro.unref();
  process.stdout.write('  … waiting for Metro');
  const until = Date.now() + 180000;
  let up = false;
  while (Date.now() < until) {
    await sleep(4000);
    process.stdout.write('.');
    up = await fetch('http://127.0.0.1:8081/status').then((r) => r.ok).catch(() => false);
    if (up) break;
  }
  process.stdout.write('\n');
  record('metro bundler', up ? 'ok' : 'fail', up ? 'serving on :8081' : 'never answered /status');
  if (!up) process.exit(1);
} else {
  record('metro bundler', 'ok', 'already running on :8081');
}

adb('reverse', 'tcp:8081', 'tcp:8081');
adb('reverse', 'tcp:8001', 'tcp:8001');
adb('logcat', '-c');

/* ---------------------------------------------------------------------- drive */

const dump = () => {
  adb('shell', 'uiautomator', 'dump', '/sdcard/ui.xml');
  return adb('shell', 'cat', '/sdcard/ui.xml');
};
const nodes = (xml) => [...xml.matchAll(/<node[^>]*>/g)].map((m) => {
  const a = (k) => (new RegExp(`${k}="([^"]*)"`).exec(m[0]) ?? [])[1] ?? '';
  const b = /bounds="\[(\d+),(\d+)]\[(\d+),(\d+)]"/.exec(m[0]);
  return {
    text: a('text'), desc: a('content-desc'), cls: a('class'), clickable: a('clickable') === 'true',
    box: b ? { x: (+b[1] + +b[3]) / 2, y: (+b[2] + +b[4]) / 2, w: +b[3] - +b[1], h: +b[4] - +b[2] } : null,
  };
});
const find = (xml, needle) => nodes(xml).find((n) =>
  n.box && n.box.w > 0 && (n.text.includes(needle) || n.desc.includes(needle)));
const tapText = async (needle, label = needle) => {
  for (let i = 0; i < 3; i++) {
    const n = find(dump(), needle);
    if (n) { adb('shell', 'input', 'tap', String(Math.round(n.box.x)), String(Math.round(n.box.y))); await sleep(2200); return true; }
    await sleep(1500);
  }
  record(`tap "${label}"`, 'fail', 'not found on screen');
  return false;
};
const shot = async (name) => {
  adb('shell', 'screencap', '-p', '/sdcard/s.png');
  const buf = execFileSync(ADB, ['exec-out', 'cat', '/sdcard/s.png'], { maxBuffer: 64 * 1024 * 1024 });
  writeFileSync(join(OUT, `${name}.png`), buf);
};
/** Is anything meaningful on screen, and did the app die? */
const health = async (name) => {
  const xml = dump();
  const texts = nodes(xml).map((n) => n.text).filter(Boolean);
  const alive = adb('shell', 'pidof', PKG).trim().length > 0;
  await shot(name);
  return { alive, texts, sample: texts.slice(0, 6).join(' · ').slice(0, 90) };
};

adb('shell', 'monkey', '-p', PKG, '-c', 'android.intent.category.LAUNCHER', '1');
// First launch downloads the entire bundle from Metro, which takes far longer than a packaged app.
await sleep(45000);
{
  const h = await health('00-cold-start');
  record('cold start', h.alive ? 'ok' : 'fail', h.sample);
}

/*
 * Sign in.
 *
 * Two things that look fine and are not: `adb shell input text` is interpreted by the *device's* shell,
 * so `!` and `@` must be escaped or the password arrives mangled; and KEYCODE_TAB does not reliably move
 * focus between React Native `TextInput`s, so each field is located and tapped by index instead of
 * tabbed into.
 */
const typeInto = async (node, value) => {
  adb('shell', 'input', 'tap', String(Math.round(node.box.x)), String(Math.round(node.box.y)));
  await sleep(900);
  // Escape for the device shell; spaces become %s for `input text`.
  const safe = value.replace(/([\\"'`$!&|;()<>*?~#])/g, '\\$1').replace(/ /g, '%s');
  adb('shell', `input text ${safe}`);
  await sleep(500);
};

const fields = nodes(dump()).filter((n) => /EditText/.test(n.cls) && n.box);
if (fields.length >= 2) {
  await typeInto(fields[0], 'student@demo.hangyul.kr');
  adb('shell', 'input', 'keyevent', 'KEYCODE_ESCAPE');
  await sleep(400);
  // Re-dump: the keyboard may have moved the layout.
  const f2 = nodes(dump()).filter((n) => /EditText/.test(n.cls) && n.box);
  await typeInto(f2[1] ?? fields[1], 'Hangyul!2026');
  adb('shell', 'input', 'keyevent', 'KEYCODE_ESCAPE');
  await sleep(600);
  await shot('01-login-filled');
  const signedIn = (await tapText('로그인')) || (await tapText('Sign in')) || (await tapText('Log in'))
    || (await tapText('계속'));
  await sleep(10000);
  const h = await health('02-after-signin');
  const stillOnLogin = h.texts.some((t) => /비밀번호|Password/i.test(t));
  record('sign in', signedIn && h.alive && !stillOnLogin ? 'ok' : 'fail',
    stillOnLogin ? `still on the login screen — ${h.sample}` : h.sample);
} else {
  record('sign in', 'fail', `expected 2 text fields on the login screen, found ${fields.length}`);
}

// Walk the screens the brief lists.
const SCREENS = [
  ['home', null], ['universities', '대학'], ['applications', '지원'], ['messages', '메시지'], ['more', '더보기'],
];
let i = 3;
for (const [name, tab] of SCREENS) {
  if (tab && !(await tapText(tab, name))) continue;
  await sleep(2500);
  const h = await health(`${String(i).padStart(2, '0')}-${name}`);
  record(`screen: ${name}`, h.alive && h.texts.length > 2 ? 'ok' : 'fail', h.sample);
  i++;
}

/* ---------------------------------------------------------------------- fatals */

const logcat = adb('logcat', '-d', '-v', 'brief');
const fatals = logcat.split('\n').filter((l) => /FATAL EXCEPTION|AndroidRuntime: *E|ReactNativeJS.*Error/.test(l));
record('no fatal exceptions', fatals.length ? 'fail' : 'ok', fatals.length ? fatals[0].slice(0, 110) : `${logcat.split('\n').length} log lines scanned`);
const secrets = logcat.match(/Hangyul!2026|test_sk_|live_sk_/g);
record('no secrets in logcat', secrets ? 'fail' : 'ok', secrets ? `${secrets.length} match(es)` : '');
writeFileSync(join(ROOT, 'docs/qa/v19/evidence/native-runtime.json'), JSON.stringify({ avd: AVD, apk: APK, log }, null, 2));

if (!ARG.includes('--keep')) {
  try { adb('emu', 'kill'); } catch { /* already gone */ }
  try { if (metro) process.kill(-metro.pid); } catch { /* already gone */ }
}

const bad = log.filter((l) => l.status === 'fail').length;
console.log(`\n${log.length} checks, ${bad} failed. Screenshots in docs/qa/v19/screenshots/native/`);
process.exit(bad ? 1 : 0);
