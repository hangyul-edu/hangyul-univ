/**
 * Generate `docs/qa/v12/PRIVACY_DATA_MAP.md` from the product's own processing inventory (V12, brief Part 24).
 *
 *     node scripts/qa/v12-privacy-data-map.mjs
 *
 * The audit and the published policy are produced from one file — `src/lib/legal/data-map.ts` — so they cannot
 * drift. A category added to the policy without a table behind it, or a table that stops being true, shows up
 * here as a diff rather than as a discrepancy somebody has to notice.
 *
 * Anything this script cannot derive (retention periods, processors) is reported as *absent* rather than filled
 * in, which is the finding, not a gap in the tooling.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const OUT = 'docs/qa/v12/PRIVACY_DATA_MAP.md';
const SRC = 'apps/marketing-web/src/lib/legal/data-map.ts';

/* The data map is plain TypeScript with no runtime dependencies, so Node's own type stripping imports it
   directly. An earlier version of this script stripped the types with regexes and mangled an inline object
   type — which is its own small lesson about hand-rolled parsers. */
const { DATA_CATEGORIES, DISCLOSURES, PROCESSORS, STATUTORY_RECORDS } =
  await import(`../../${SRC}`);

/** Confirm each named table actually exists in the live schema rather than only in the comment. */
function liveTables() {
  try {
    const out = execFileSync(
      '.venv/bin/python',
      ['-c', "from app.models.base import Base; import app.models; print('\\n'.join(sorted(Base.metadata.tables)))"],
      { cwd: 'server', encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] },
    );
    return new Set(out.trim().split('\n'));
  } catch {
    return null;
  }
}
const tables = liveTables();
const check = (t) => (tables === null ? '?' : tables.has(t) ? '✓' : '**missing**');

const RECIPIENT = {
  HANGYUL: 'Hangyul',
  AGENCY: 'assigned agency',
  UNIVERSITY: 'university applied to',
  SPONSOR: 'sponsor named by the student',
};

const lines = [];
const p = (s = '') => lines.push(s);

p('# V12 — privacy data map');
p();
p('*Generated by `scripts/qa/v12-privacy-data-map.mjs` from `apps/marketing-web/src/lib/legal/data-map.ts`, which');
p('is the same file `/privacy` renders from. Do not edit by hand: edit the data map and re-run.*');
p();
p('This is the audit the brief\'s Part 24 asks for — database/API field → purpose → recipient → retention →');
p('policy section — produced from the product rather than from a legal template. Where a column reads');
p('**not approved**, that is the finding: no value for it exists anywhere in this repository, and the published');
p('policy omits it rather than inventing one.');
p();

p('## 1. Categories processed');
p();
p('| Policy section | Category | Tables | Recipients | Only when a service needs it |');
p('|---|---|---|---|---|');
for (const c of DATA_CATEGORIES) {
  const tbl = c.tables.map((t) => `\`${t}\` ${check(t)}`).join('<br>');
  const rec = c.recipients.map((r) => RECIPIENT[r]).join(', ');
  p(`| §1 \`collect.${c.key}\` | ${c.key} | ${tbl} | ${rec} | ${c.optional ? 'yes' : 'no'} |`);
}
p();

p('## 2. Fields, per category');
p();
for (const c of DATA_CATEGORIES) {
  p(`### ${c.key}`);
  p();
  for (const f of c.fields) p(`- \`${f}\``);
  p();
}

p('## 3. Disclosure to third parties');
p();
p('| Recipient | Consent record | What puts the data there | Policy section |');
p('|---|---|---|---|');
for (const d of DISCLOSURES) {
  p(`| ${d.key} | \`${d.consent}\` | ${d.trigger} | §3 |`);
}
p();
p('Sharing is driven by application state, not by the policy text: a university receives an application when it');
p('is submitted to that university, and an agency receives a case when it is assigned. The page says so');
p('explicitly, so no reader concludes that every university holds every document.');
p();

p('## 4. Processors');
p();
if (PROCESSORS.length === 0) {
  p('**None configured.** Verified against the running system, not assumed:');
  p();
  p('| Would-be processor | Production state today |');
  p('|---|---|');
  p('| File storage | local filesystem (`app/core/storage.py`); no S3/object-store credentials configured |');
  p('| Malware scanning | no-op scanner that records `SKIPPED` (`MalwareScanner`) |');
  p('| Email / SMS / chat | not connected; in-app messages only |');
  p('| Payment | development stub provider (`payments.provider == "demo"`) |');
  p();
  p('§4 of the policy therefore states that no processor currently handles personal information on Hangyul\'s');
  p('behalf, and §5 that no overseas-transfer processor is in use. Both become false the moment a vendor is');
  p('contracted, which is why they are rendered from `PROCESSORS` rather than written as prose.');
} else {
  p('| Processor | Work | Country |');
  p('|---|---|---|');
  for (const x of PROCESSORS) p(`| ${x.name} | ${x.purpose} | ${x.country} |`);
}
p();

p('## 5. Retention');
p();
p('| Record | Period | Source of the period |');
p('|---|---|---|');
for (const r of STATUTORY_RECORDS) {
  const period = 'months' in r ? `${r.months} months` : `${r.years} years`;
  p(`| ${r.key} | ${period} | Korean e-commerce consumer-protection law |`);
}
p('| applicant documents | **not approved** | no value exists; `LEGAL_DEPENDENCIES.md` L8 is `OPEN` |');
p('| account and profile | **not approved** | as above |');
p('| audit and access logs | **not approved** | as above |');
p();
p('The policy publishes the rule it does follow — purpose achieved, then destroyed without delay — and the four');
p('statutory commerce periods. It publishes no period for documents, accounts or logs, and no retention job');
p('exists to enforce one. This is a launch blocker, recorded in REPORT §92.');
p();

p('## 6. Cookies and client storage');
p();
p('| What | Where | Sent to the server | Consent needed |');
p('|---|---|---|---|');
p('| refresh token | httpOnly cookie, `SameSite=Lax`, path `/api/v1/auth`, one per client app | yes, to that path only | no — strictly necessary |');
p('| `hg.locale` | `localStorage` | no | no |');
p('| `hg.<product>.sb`, `hg.<product>.theme`, `hg.student.compare`, `hg.student.currency`, `hg.uni.openNext`, `hg.agency.prefs` | `localStorage` | no | no |');
p();
p('A repository-wide scan for Google Analytics, Google Tag Manager, Segment, Mixpanel, Hotjar, Meta Pixel,');
p('Sentry, PostHog, Amplitude and Microsoft Clarity returns **nothing**. There is no advertising, behavioural');
p('tracking or third-party analytics, so there is no consent-requiring cookie — and therefore no cookie banner.');
p('Hangyul\'s own `analytics_events` table is first-party and server-side.');
p();

p('## 7. Claims checked against the code');
p();
p('| Policy claim | Verified in | Holds |');
p('|---|---|---|');
p('| No card data is stored | `app/models/business.py` `Payment` — provider ref, status, amount, sanitised payload only | yes |');
p('| Passport number is masked | `student_profiles.passport_number_masked`, last 3 characters | yes |');
p('| Document files have no public URL | HMAC-signed 5-minute URLs after an authorisation check (`docs/SECURITY.md`) | yes |');
p('| Every document access is logged | `audit_logs` with `subject_user_id` | yes |');
p('| Out-of-tenant records are not disclosed | `app/services/access.py`, 404 not 403; `server/tests/test_security.py` | yes |');
p('| Passwords cannot be reversed | Argon2id (`argon2-cffi`) | yes |');
p('| Uploads are scanned | hook exists; **development uses a no-op scanner** | partly — §8 says uploads are scanned before review, which is true of the pipeline and not yet of production |');
p();
p('The last row is the only claim in the policy that production configuration does not yet fully support. It is');
p('listed in REPORT §92 with the storage and scanning dependencies it belongs to.');
p();

mkdirSync('docs/qa/v12', { recursive: true });
writeFileSync(OUT, `${lines.join('\n')}\n`, 'utf8');
console.log(`→ ${OUT}`);
console.log(`  ${DATA_CATEGORIES.length} categories · ${DISCLOSURES.length} disclosures · ${PROCESSORS.length} processors · schema check ${tables ? 'on' : 'unavailable'}`);
