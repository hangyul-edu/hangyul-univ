#!/usr/bin/env node
// V29 — renders infra/nginx/hangyul.conf from infra/csp.json. `--check` exits 1 if the committed file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { headerFor, loadPolicy, problems, ROOT } from './csp.mjs';

const policy = loadPolicy();
const bad = problems(policy);
if (bad.length) { console.error(bad.join('\n')); process.exit(1); }
const hdr = policy.report_only ? 'Content-Security-Policy-Report-Only' : 'Content-Security-Policy';
const sec = (app) => `    add_header ${hdr} "${headerFor(policy, app)}" always;
    add_header Strict-Transport-Security "${policy.hsts}" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header X-Frame-Options "DENY" always;
    add_header Referrer-Policy "strict-origin-when-cross-origin" always;
    add_header Cross-Origin-Opener-Policy "same-origin-allow-popups" always;
    add_header Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=(self)" always;`;

const blocks = Object.entries(policy.apps).map(([app, c]) => `# app: ${app}
server {
    listen 80;
    listen [::]:80;
    server_name ${c.server_name};
    return 301 https://$host$request_uri;   # HTTPS only
}

server {
    listen 443 ssl;
    listen [::]:443 ssl;
    http2 on;
    server_name ${c.server_name};
    ssl_certificate     /etc/ssl/hangyul/${app}.fullchain.pem;
    ssl_certificate_key /etc/ssl/hangyul/${app}.key;
    include /etc/nginx/snippets/hangyul-tls.conf;

    root ${c.root};
    index index.html;
    client_max_body_size 16m;   # uploads: 15 MB limit enforced by the API

${sec(app)}

    # Same-origin API: auth cookies stay first-party and connect-src 'self' suffices. The API sets its own strict CSP.
    location /api/ {
        proxy_pass ${policy.api_upstream};
        proxy_set_header Host $host;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto https;
        proxy_read_timeout 60s;
    }

    location /assets/ {
        add_header Cache-Control "public, max-age=31536000, immutable";
${sec(app).replace(/^ {4}/gm, '        ')}
        try_files $uri =404;
    }

    location / {
        add_header Cache-Control "no-cache";
${sec(app).replace(/^ {4}/gm, '        ')}
        try_files $uri $uri/ /index.html;
    }
}
`);

const out = `# GENERATED by scripts/ops/gen-nginx.mjs from infra/csp.json — do not edit by hand (V29).
# Static Vite builds behind nginx; TLS terminates here. Replace server_name/cert paths per deployment in infra/csp.json.
# nginx does not inherit add_header into a location that declares its own, so the security headers are repeated there.

# Shared TLS settings (install as /etc/nginx/snippets/hangyul-tls.conf):
#   ssl_protocols TLSv1.2 TLSv1.3; ssl_prefer_server_ciphers off; ssl_session_cache shared:SSL:10m; ssl_stapling on;

${blocks.join('\n')}`;
const target = resolve(ROOT, 'infra/nginx/hangyul.conf');
if (process.argv.includes('--check')) {
  let cur = '';
  try { cur = readFileSync(target, 'utf8'); } catch { /* missing */ }
  if (cur !== out) { console.error('infra/nginx/hangyul.conf is stale — run node scripts/ops/gen-nginx.mjs'); process.exit(1); }
  console.log('infra/nginx/hangyul.conf is up to date');
} else {
  writeFileSync(target, out);
  console.log(`wrote ${target}`);
}
