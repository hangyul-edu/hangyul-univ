/**
 * V29 (brief §30, option B): a console offers a language only when its console namespace is **complete**.
 *
 * V28 let an Arabic counsellor pick Arabic and then read a console that was ~84 % English. Fully translating the
 * ~4,400 agency + university console keys for 33 locales is a funded translation programme, not a release step,
 * so the product decision is the honest one: the Agency and University consoles (web and native) list only the
 * locales whose namespace has every key the English source has — counted with each locale's own CLDR plural
 * categories (Korean has no `_one` form, so a missing `_one` key is not a gap there). Student and Marketing keep
 * their broader, separately gated lists.
 *
 *   node scripts/i18n/v29/console-locales.mjs          write packages/i18n/src/console-locales.ts
 *   node scripts/i18n/v29/console-locales.mjs --check  fail if the written list is stale or offers an incomplete locale
 */
import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const LOC = resolve(ROOT, 'packages/i18n/locales');
const OUT = resolve(ROOT, 'packages/i18n/src/console-locales.ts');
const CONSOLES = { agency: 'agency', university: 'university' };

const flat = (o, p = '', out = {}) => {
  for (const [k, v] of Object.entries(o)) {
    if (v && typeof v === 'object') flat(v, `${p}${k}.`, out); else out[`${p}${k}`] = v;
  }
  return out;
};
const PLURAL = /_(zero|one|two|few|many|other)$/;

function coverage(ns, loc) {
  const en = flat(JSON.parse(readFileSync(resolve(LOC, 'en', `${ns}.json`), 'utf8')));
  const f = resolve(LOC, loc, `${ns}.json`);
  const mine = existsSync(f) ? flat(JSON.parse(readFileSync(f, 'utf8'))) : {};
  let cats;
  try { cats = new Set(new Intl.PluralRules(loc).resolvedOptions().pluralCategories); } catch { cats = new Set(['other']); }
  let need = 0; const missing = [];
  for (const k of Object.keys(en)) {
    const m = PLURAL.exec(k);
    if (m && m[1] !== 'other' && !cats.has(m[1])) continue; // a form this language does not have
    need += 1;
    const v = mine[k] ?? (m ? mine[k.replace(PLURAL, '')] : undefined);
    if (typeof v !== 'string' || !v.trim()) missing.push(k);
  }
  return { need, missing };
}

const locales = readdirSync(LOC).filter((d) => !d.startsWith('_') && existsSync(resolve(LOC, d, 'common.json')));
const result = {};
const report = {};
for (const [app, ns] of Object.entries(CONSOLES)) {
  result[app] = ['en'];
  for (const loc of locales) {
    if (loc === 'en') continue;
    const c = coverage(ns, loc);
    report[`${app}:${loc}`] = `${c.need - c.missing.length}/${c.need}`;
    if (c.missing.length === 0) result[app].push(loc);
  }
  result[app].sort();
}

const text = `/**
 * Generated by scripts/i18n/v29/console-locales.mjs — do not edit by hand.
 *
 * The locales whose console namespace is complete, and therefore the only ones the Agency and University consoles
 * (web and native) offer or boot into (V29, brief §30). Coverage at generation:
${Object.entries(report).filter(([, v]) => !v.startsWith('0/')).map(([k, v]) => ` *   ${k.padEnd(24)} ${v}`).join('\n')}
 *   (every other locale: 0 keys)
 */
export const CONSOLE_LOCALES = ${JSON.stringify(result)} as const;

export type ConsoleApp = keyof typeof CONSOLE_LOCALES;

export function isConsoleLocale(app: ConsoleApp, code: string): boolean {
  return (CONSOLE_LOCALES[app] as readonly string[]).includes(code);
}

/** The locale a console boots into: the requested one when complete, else Korean for a Korean reader, else English. */
export function consoleLocale(app: ConsoleApp, code: string): string {
  if (isConsoleLocale(app, code)) return code;
  return code.startsWith('ko') ? 'ko' : 'en';
}
`;
if (process.argv.includes('--check')) {
  const have = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (have !== text) { console.error('packages/i18n/src/console-locales.ts is stale — run node scripts/i18n/v29/console-locales.mjs'); process.exit(1); }
  console.log(`console locales: agency ${result.agency.join(',')} · university ${result.university.join(',')} (all complete)`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote console-locales.ts: agency ${result.agency.join(',')} · university ${result.university.join(',')}`);
}
