/**
 * Inline the market flags into a module the native apps can bundle (V17).
 *
 *     node scripts/i18n/generate-flag-module.mjs        # writes packages/mobile-ui/src/flags.generated.ts
 *     node scripts/i18n/generate-flag-module.mjs --check # fails if the module is out of date
 *
 * **Why a generated module and not a file read.** The web apps publish `apps/flags/*.svg` and `<Flag>`
 * loads them by URL. Metro has no `public/` directory and no SVG loader, so on a phone that URL resolves
 * to nothing — which is why the native language picker had names and no flags (REPORT §149), while the
 * web picker's own bug looked identical and had a completely different cause.
 *
 * Thirty-two flags are 33 KB of SVG in total, so inlining them is cheaper than any loader: one import,
 * no network, no asset pipeline, and the same artwork the web uses rather than a second set that can
 * drift. `react-native-svg`'s `SvgXml` renders the string directly.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SRC = join(ROOT, 'apps', 'flags');
const OUT = join(ROOT, 'packages', 'mobile-ui', 'src', 'flags.generated.ts');

const { MARKETS } = await import(pathToFileURL(join(ROOT, 'packages/i18n/src/markets.ts')).href);

/** Strip the parts of an SVG that do nothing on screen: comments, XML prologs, and surrounding space. */
function tidy(svg) {
  return svg
    .replace(/<\?xml[^>]*\?>/g, '')
    .replace(/<!DOCTYPE[^>]*>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s*\n\s*/g, ' ')
    .replace(/>\s+</g, '><')
    .trim();
}

const available = new Set(readdirSync(SRC).filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4)));
const rows = [];
const missing = [];
for (const m of MARKETS) {
  if (!available.has(m.asset)) { missing.push(`${m.code} (${m.asset}.svg)`); continue; }
  rows.push([m.asset, tidy(readFileSync(join(SRC, `${m.asset}.svg`), 'utf8'))]);
}
if (missing.length) {
  console.error(`! ${missing.length} market(s) have no flag asset: ${missing.join(', ')}`);
  process.exit(1);
}

const body = `/**
 * Generated by \`scripts/i18n/generate-flag-module.mjs\` — do not edit.
 *
 * The ${rows.length} market flags, inlined so a React Native bundle can render them without an asset
 * pipeline. Source of truth: \`apps/flags/*.svg\`, the same files the web apps publish. Provenance for each
 * one is recorded beside it (\`apps/flags/*.PROVENANCE.md\`).
 */
export const FLAG_SVG: Readonly<Record<string, string>> = {
${rows.map(([code, svg]) => `  ${JSON.stringify(code)}: ${JSON.stringify(svg)},`).join('\n')}
};
`;

const current = (() => { try { return readFileSync(OUT, 'utf8'); } catch { return null; } })();
if (process.argv.includes('--check')) {
  if (current !== body) {
    console.error('! packages/mobile-ui/src/flags.generated.ts is out of date — run node scripts/i18n/generate-flag-module.mjs');
    process.exit(1);
  }
  console.log(`flag module: up to date (${rows.length} flags)`);
} else {
  writeFileSync(OUT, body);
  console.log(`flag module: ${rows.length} flags, ${(body.length / 1024).toFixed(1)} KB → packages/mobile-ui/src/flags.generated.ts`);
}
