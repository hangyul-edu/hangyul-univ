/**
 * V11 — record, per locale, what the public homepage actually shows (brief: "Preserve the existing
 * translation-status honesty … Never claim human review without evidence").
 *
 * V11 replaced the homepage's copy with the Koreanasha source. The Korean is canonical and the English is a
 * translation of it; the other 56 locales have no `v11.*` strings yet and fall back to English at runtime.
 * That fallback is verified, not assumed — `scripts/qa/_v11fallback.mjs` loads the page in those locales and
 * checks that no raw key reaches the screen — but it is still a **coverage regression** against V10, where the
 * marketing namespace was translated everywhere, and it is written down as one rather than left to be noticed.
 *
 *   node scripts/i18n/v11-translation-status.mjs
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const dir = resolve(root, 'packages/i18n/locales');
const flat = (o, p = '') => Object.entries(o).flatMap(([k, v]) => (v && typeof v === 'object' ? flat(v, `${p}${k}.`) : [`${p}${k}`]));
/** Some locales ship no marketing bundle at all; they are an empty set, not an error. */
const keys = (loc) => {
  const f = resolve(dir, loc, 'marketing.json');
  if (!existsSync(f)) return new Set();
  return new Set(flat(JSON.parse(readFileSync(f, 'utf8'))));
};

const v11 = [...keys('en')].filter((k) => k.startsWith('v11.'));
const CANONICAL = JSON.parse(readFileSync(resolve(root, 'docs/qa/v11/koreanasha-copy.json'), 'utf8')).source.locales;
const locales = readdirSync(dir).filter((d) => !d.startsWith('_')).sort();

const status = {};
for (const loc of locales) {
  const have = keys(loc);
  const n = v11.filter((k) => have.has(k)).length;
  status[loc] = {
    homepage_keys: `${n}/${v11.length}`,
    state: CANONICAL.includes(loc) ? 'CANONICAL_SOURCE' : n === v11.length ? 'SYNTHETIC_REVIEWED' : 'FALLS_BACK_TO_EN',
    has_marketing_bundle: have.size > 0,
    human_reviewed: false,
  };
}

writeFileSync(resolve(root, 'docs/qa/v11/translation-status.json'), `${JSON.stringify({
  $comment: 'Generated by scripts/i18n/v11-translation-status.mjs. No locale is HUMAN_REVIEWED; none may be labelled so without a named reviewer and a date.',
  generatedAt: new Date().toISOString().slice(0, 10),
  states: {
    CANONICAL_SOURCE: 'Korean and Russian — the owner-supplied Koreanasha copy itself, both written by the company (its audience is Russian-speaking), verified character-for-character by scripts/qa/v11-copy-fidelity.mjs.',
    SYNTHETIC_REVIEWED: 'An AI translation of the Korean source, re-read against it in the same session. No human translator has seen it.',
    FALLS_BACK_TO_EN: 'No v11 strings in this locale. The homepage renders the English; verified to leak no raw keys. A regression against V10 marketing coverage — see REPORT §82.',
  },
  homepageKeyCount: v11.length,
  locales: status,
}, null, 2)}\n`);

const counts = Object.values(status).reduce((a, s) => ({ ...a, [s.state]: (a[s.state] ?? 0) + 1 }), {});
console.log(Object.entries(counts).map(([k, v]) => `${k}: ${v}`).join('  '));
