#!/usr/bin/env node
/**
 * V32 — write docs/qa/v32/l10n/LANGUAGE_SIGNOFF.md from what was actually applied.
 *
 *   node scripts/i18n/v32/signoff.mjs
 *
 * Per locale: the review jobs that exist, the patch files that came back, strings changed (from the applied log, the
 * only record that counts), how many of them created a translation that did not exist before, and every `_notes`
 * line the reviewers left for the owner. Status for every row is SYNTHETIC_NATIVE_REVIEWED_V32 — no human review.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(new URL('../../..', import.meta.url).pathname);
const D = (p) => path.join(ROOT, 'docs/qa/v32/l10n', p);
const JOB_KINDS = ['marketing-common', 'consoles', 'student-mobile', 'deep'];
const markets = [...fs.readFileSync(path.join(ROOT, 'packages/i18n/src/markets.ts'), 'utf8').matchAll(/locale: ?'([^']+)'/g)].map((m) => m[1]);
const extra = fs.readdirSync(D('jobs')).map((f) => f.match(/^(.+)-deep\.json$/)?.[1]).filter(Boolean); // offered in the Student app though not a market (ur, zh-Hant)
const locales = [...new Set([...markets, ...extra])].filter((l) => l !== 'ko').sort((a, b) => (a === 'en' ? -1 : b === 'en' ? 1 : a.localeCompare(b)));

const rows = []; const notes = []; let total = 0, created = 0;
for (const loc of locales) {
  const jobs = JOB_KINDS.filter((k) => fs.existsSync(D(`jobs/${loc}-${k}.json`)));
  const patches = JOB_KINDS.filter((k) => fs.existsSync(D(`patches/${loc}-${k}.json`)));
  const log = fs.existsSync(D(`applied/${loc}.json`)) ? JSON.parse(fs.readFileSync(D(`applied/${loc}.json`), 'utf8')) : [];
  const n = log.length; const c = log.filter((x) => x.old === undefined || x.old === null).length;
  total += n; created += c;
  const missing = jobs.filter((k) => !patches.includes(k));
  rows.push(`| ${loc} | ${patches.length}/${jobs.length}${missing.length ? ` (missing: ${missing.join(', ')})` : ''} | ${n} | ${c} |`);
  for (const k of patches) {
    const p = JSON.parse(fs.readFileSync(D(`patches/${loc}-${k}.json`), 'utf8'));
    for (const line of p._notes ?? []) notes.push(`- **${loc}** (${k}): ${String(line).replace(/\s+/g, ' ').trim()}`);
  }
}
const out = `# V32 language sign-off

Generated by \`scripts/i18n/v32/signoff.mjs\` from \`docs/qa/v32/l10n/applied/*.json\` (the applied-change log) and the
reviewers' patch files. **Status of every locale: \`SYNTHETIC_NATIVE_REVIEWED_V32\` — a native-level model reviewer
per locale, five passes (meaning, naturalness, clarity, tone, back-check) against \`docs/I18N_GLOSSARY.md\`. No human has
reviewed any of it.**

Every applied string passed \`scripts/i18n/v32/apply-patch.mjs\`: placeholders identical to the English, no empty value,
no English left where the Korean differs (unless the reviewer kept an English loan term deliberately, \`--allow-same\`),
no key the English source does not have.

| Locale | Review jobs returned | Strings changed | of which previously missing |
|---|---|---|---|
${rows.join('\n')}
| **total** | | **${total}** | **${created}** |

"Previously missing" = the locale had no string at all and the screen rendered English (mostly the Agency and University
consoles and the native staff apps).

## Reviewer notes for the owner

Ambiguities each reviewer resolved, and decisions they left open (brand rendering, plan terminology, institution-type
glosses, localized example placeholders, register). Nothing here is applied silently beyond what the patch contains.

${notes.join('\n')}
`;
fs.writeFileSync(D('LANGUAGE_SIGNOFF.md'), out);
console.log(`LANGUAGE_SIGNOFF.md: ${locales.length} locales, ${total} strings changed (${created} previously missing), ${notes.length} reviewer notes`);
